      ja: '入門向けに再構成しやすい候補です。まず全区間ではなく10-20kmの体験区間と復帰動線を決めます。',
      zh: '适合重新设计为入门路线。建议先选择10-20公里体验区间，并确定回程方式。',
      es: 'Buen candidato para rediseñar como ruta inicial. Empieza con 10-20 km y un regreso claro.'
